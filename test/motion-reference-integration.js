'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const source = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const html = source('renderer/index.html');
const app = source('renderer/app.js');
const main = source('main.js');
const ai = source('lib/ai.js');
const motion = source('lib/motion-design.js');
const readme = source('README.md');
const attribution = source('docs/REFERENCE_INTEGRATION_ATTRIBUTION.md');
const pkg = JSON.parse(source('package.json'));
assert(html.includes('id=\"bReferenceReport\"') && html.includes('id=\"dReferenceReport\"'), 'human editor exposes reference breakdown');
assert(app.includes('renderReferenceReport') && app.includes('rExport') && app.includes('Go to shot'), 'human editor can inspect, navigate and export analysis');
assert(main.includes('temporal frame-comparison evidence') && main.includes('avoid duplicating camera motion') && main.includes('analyzeVisualFrames'), 'copy-to-template workflow performs batched temporal vision analysis and prevents double zoom');
assert(ai.includes('blueprint: (r.blueprint || [])') && ai.includes('audio: r.audio ?') && ai.includes('audioAlignment,visualAnalysis,captionText,transcript'), 'AI analysis tool exposes per-shot audio/visual blueprint evidence');
assert(motion.includes('geometrySvg') && motion.includes('animationKeyframes') && motion.includes('wireframe-cube'), 'procedural geometry and animation are shared as code features, not installed skills');
assert(attribution.includes('independently written') && attribution.includes('does not copy its code'), 'reference integration boundaries are documented');
assert(readme.includes('under active development') && readme.includes('Apache License 2.0'), 'README describes known scope limits and licensing');
assert(!JSON.stringify(pkg.dependencies || {}).includes('three'), 'no third-party Three.js runtime is bundled for the procedural motion-design features');
console.log('Motion/reference integration static checks passed.');
