'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const pkg = JSON.parse(read('package.json'));
const lock = JSON.parse(read('package-lock.json'));
const packageNative = read('scripts/package-native.ps1');
const buildNative = read('scripts/build-native.ps1');
const notices = read('THIRD_PARTY_NOTICES.md');
const ffmpegEngine = read('lib/ffmpeg.js');
const runtimeRequirements = read('RUNTIME_REQUIREMENTS.md');
const ffmpegInstaller = read('scripts/install-ffmpeg.ps1');
const releaseInstaller = read('scripts/Install-Frosty.ps1');
const nsisInstaller = read('build/installer.nsh');

assert.equal(pkg.license, 'Apache-2.0');
assert.equal(pkg.dependencies?.['ffmpeg-static'], undefined, 'GPL ffmpeg-static wrapper must not be a Frosty runtime dependency');
assert.equal(lock.packages[''].dependencies?.['ffmpeg-static'], undefined, 'lockfile must not declare ffmpeg-static as a runtime dependency');
assert.equal(lock.packages['node_modules/ffmpeg-static'], undefined, 'lockfile must not retain the GPL ffmpeg-static package');
assert.doesNotMatch(packageNative, /node_modules[\\/]ffmpeg-static/i, 'native package script must not download or copy ffmpeg-static');
assert.doesNotMatch(buildNative, /node_modules[\\/]ffmpeg-static/i, 'native build script must not copy ffmpeg-static');
assert.match(packageNative, /not bundled by Frosty/i, 'release build must record the external runtime boundary');
assert.match(buildNative, /not bundled or relicensed by Frosty/i, 'native build must record the external runtime boundary');
assert.match(ffmpegEngine, /process\.env\.FROSTY_FFMPEG/, 'FFmpeg override remains available');
assert.doesNotMatch(ffmpegEngine, /require\(['"]ffmpeg-static['"]\)/, 'runtime code must not import the GPL wrapper');
assert.match(notices, /FFmpeg \/ FFprobe are external prerequisites \(not bundled\)/, 'third-party notice states the external prerequisite policy');
assert.match(notices, /FFmpeg is not licensed under Apache-2\.0/i, 'FFmpeg is not misrepresented as Apache-licensed');
assert.match(runtimeRequirements, /does not bundle FFmpeg or FFprobe/i, 'released runtime documentation explains external tools');
assert.ok(pkg.build.files.includes('RUNTIME_REQUIREMENTS.md'), 'Electron build contains runtime prerequisite documentation');
assert.equal(pkg.build.extraResources?.[0]?.from, 'scripts/install-ffmpeg.ps1', 'NSIS helper is copied outside app.asar');
assert.equal(pkg.build.nsis.include, 'build/installer.nsh', 'Electron NSIS installer uses the dependency hook');
assert.match(ffmpegInstaller, /Gyan\.FFmpeg/, 'automatic install uses the exact WinGet FFmpeg package ID');
assert.match(ffmpegInstaller, /GPL-3\.0/, 'helper identifies the package license');
assert.match(ffmpegInstaller, /--accept-package-agreements/);
assert.match(releaseInstaller, /Install-Frosty|install-ffmpeg/);
assert.match(read('scripts/Install-Frosty.cmd'), /ExecutionPolicy Bypass/);
assert.match(nsisInstaller, /MessageBox MB_YESNO/, 'NSIS requests user consent before auto-install');
assert.match(nsisInstaller, /\$\{ifNot\} \$\{isUpdated\}/, 'updates do not re-prompt for installation');
assert.match(runtimeRequirements, /can offer to install `Gyan\.FFmpeg`/);
console.log('FFmpeg licensing boundary passed: Frosty Apache-2.0 source does not bundle or import ffmpeg-static/FFmpeg binaries.');
