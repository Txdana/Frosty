'use strict';
const assert = require('assert');
const Motion = require('../lib/motion-design');
const TL = require('../lib/timeline');
assert(Motion.TYPES.includes('wireframe-cube') && Motion.TYPES.includes('perspective-grid'), 'geometry based on projected vector line-art concepts is available');
assert(Motion.TYPES.includes('lower-third') && Motion.TYPES.includes('kinetic-caption'), 'human-facing editorial building blocks are available');
assert(Motion.ANIMATIONS.includes('drift-zoom') && Motion.ANIMATIONS.includes('rotate-in'), 'keyframed motion presets are present');
const svg = Motion.generateSvg({ type: 'title-card', theme: 'cobalt', title: '<script>alert(1)</script>', subtitle: 'A & B', shape: 'wireframe-cube', width: 1280, height: 720 });
assert(svg.startsWith('<?xml') && svg.includes('<svg') && svg.includes('wireframe') === false, 'generator returns SVG document');
assert(svg.includes('&lt;script&gt;') && svg.includes('A &amp; B'), 'user-supplied text is XML escaped');
assert(!/<script\b/i.test(svg), 'untrusted text cannot create script nodes in SVG');
assert(svg.includes('stroke=') && svg.includes('fill='), 'SVG contains real vector shapes and visual elements');
assert.throws(() => Motion.generateSvg({ type: 'remote-code' }), /Unsupported motion graphic type/, 'only enumerated design blocks are accepted');
const layer = TL.addLayer(TL.empty(), { path: 'overlay.png', name: 'Heading', duration: 4, type: 'image', hasAudio: false }, 2, 2);
layer.x = 0.5; layer.y = 0.5; layer.scale = 1;
Motion.applyAnimation(layer, 'fade-up', 4);
assert(layer.keyframes.opacity.length >= 2 && layer.keyframes.y.length >= 2, 'animation becomes editable timeline keyframes');
assert.strictEqual(layer.animationPreset, 'fade-up', 'selected animation remains inspectable');
assert.throws(() => Motion.applyAnimation(layer, 'execute-shell', 4), /Unsupported animation preset/, 'unknown animation presets are rejected');
const variants = Motion.TYPES.map((type) => Motion.generateSvg({ type, title: 'Test', subtitle: 'Native graphic' }));
assert.strictEqual(variants.length, 12); assert(variants.every((x) => x.includes('<svg')), 'all advertised graphic types render an SVG');
console.log('Motion Studio generation, escaping, and editable keyframe tests passed.');
