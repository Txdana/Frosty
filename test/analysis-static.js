const assert = require('assert');
const ff = require('../lib/ffmpeg');
const analysis = require('../lib/analysis');
const TL = require('../lib/timeline');
assert(ff.PRESETS['YouTube 1080p 60fps'].fps === 60, '60fps profile');
assert(ff.PRESETS['HEVC 4K'].videoCodec === 'libx265', 'HEVC profile');
assert(ff.PRESETS['Small File 720p'].videoBitrate === '2M', 'small-file profile bitrate');
assert.strictEqual(analysis.parseMetric('RMS level dB: -18.2', 'RMS level dB'), -18.2);
const singleReport = { source: '/tmp/clip.mp4', name: 'clip.mp4', analyzedAt: '2026-10-27T00:00:00.000Z', summary: { durationSeconds: 3, resolution: '640x360' }, scenes: [1], sceneSegments: [{ start: 0, end: 3, duration: 3, caption: 'hello' }], audio: { integratedLufs: -16, peakDbfs: -2 }, warnings: [] };
assert(analysis.exportReport(singleReport, 'csv').includes('clip.mp4'), 'single-source CSV export includes the source');
assert(analysis.exportReport(singleReport, 'html').includes('hello'), 'single-source HTML export includes scene details');
assert.deepStrictEqual(analysis.parseLoudness('Integrated loudness: I: -16.7 LUFS\nLoudness range: LRA: 5.2 LU\nTrue peak: Peak: -1.2 dBFS'), { integratedLufs: -16.7, loudnessRangeLu: 5.2, truePeakDbfs: -1.2 });
const tl = TL.empty(); TL.addClip(tl, { path: 'sample.mp4', name: 'sample.mp4', duration: 4, hasAudio: true });
const exportPlan = ff.buildExport(tl, '/tmp/frosty-test.mp4', { ...ff.PRESETS['YouTube 1080p 60fps'], normalizeAudio: true });
assert(exportPlan.args.includes('libx264') && exportPlan.args.some(x => x.includes('fps=60')), 'profile values should reach export graph');
assert(exportPlan.args.includes('loudnorm=I=-16:TP=-1.5:LRA=11'), 'normalization filter should reach export graph');
tl.mode = 'free';
const freePlan = ff.buildExport(tl, '/tmp/frosty-test-free.mp4', { ...ff.PRESETS['HEVC 4K'], audioLimiter: true });
assert(freePlan.args.includes('libx265') && freePlan.args.includes('alimiter=limit=0.95:level=false'), 'free timeline must honor codec and limiter');
console.log('analysis/profile static tests passed');
