'use strict';
const assert = require('assert');
const fs = require('fs');
const TL = require('../lib/timeline');
const safety = require('../lib/agent-safety');
const aiSource = fs.readFileSync(require.resolve('../lib/ai'), 'utf8');
const mainSource = fs.readFileSync(require.resolve('../main'), 'utf8');
const preloadSource = fs.readFileSync(require.resolve('../preload'), 'utf8');
const uiSource = fs.readFileSync(require.resolve('../renderer/app.js'), 'utf8');
const timeline = TL.empty();
const clip = TL.addClip(timeline, { path: '/tmp/clip.mp4', name: 'clip.mp4', duration: 10 });
const before = safety.snapshot(timeline);
const after = safety.snapshot(timeline); after.video[0].out = 7;
const result = safety.validateEdit(before, after);
assert(result.valid && result.verified, 'structurally valid edits are verified');
assert.strictEqual(result.diff.changed.length, 1, 'changed clip is surfaced for review');
assert.strictEqual(result.diff.changed[0].id, clip.id);
assert.strictEqual(safety.permissionForTool('web_search', {}), false, 'web access defaults to denied');
assert.strictEqual(safety.permissionForTool('download_media', { downloads: true }), true);
assert.strictEqual(safety.permissionForTool('generate_image', { imageGeneration: true }), true);
assert.strictEqual(safety.permissionForTool('apply_ops', {}), true, 'local timeline edits do not require external permission');
assert.strictEqual(safety.permissionForTool('get_timeline', {}), true, 'known local inspection tools remain available');
assert.strictEqual(safety.permissionForTool('future_unregistered_tool', { web: true, downloads: true, imageGeneration: true }), false, 'unrecognized tools fail closed instead of inheriting permissions');
assert(mainSource.includes('nodeIntegration: false'), 'Electron renderer has Node integration disabled');
assert(mainSource.includes('contextIsolation: true') && mainSource.includes('sandbox: true'), 'Electron renderer is context-isolated and sandboxed');
assert(mainSource.includes("win.webContents.on('will-navigate'"), 'Electron blocks renderer navigation away from its trusted local UI');
assert(mainSource.includes("win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }))"), 'Electron denies unreviewed child windows');
assert(preloadSource.includes('const allowedEvents = new Set(['), 'Electron preload exposes an explicit IPC event allowlist');
assert(preloadSource.includes('if (!allowedEvents.has(channel) || typeof callback !== \'function\')'), 'Electron preload rejects unapproved IPC event subscriptions and invalid callbacks');
assert(preloadSource.includes('ipcRenderer.removeListener(channel, listener)'), 'Electron event subscriptions can be disposed without leaking listeners');
const bad = safety.snapshot(after); bad.video[0].out = bad.video[0].in;
const invalid = safety.validateEdit(before, bad);
assert.strictEqual(invalid.valid, false, 'invalid timeline changes fail validation');
assert(invalid.errors.some(x => /source range/.test(x)));
assert(aiSource.includes('permissionForTool(call.function.name, allowed)'), 'agent checks permissions before executing tools');
assert(mainSource.includes('assets = [], permissions = {}'), 'IPC receives explicit permission choices');
assert(uiSource.includes('window.confirm(review)'), 'renderer requires user approval before applying edits');
assert(uiSource.includes('Undo is available'), 'accepted timeline edits have a visible undo path');
console.log('Agent safety checks passed');
