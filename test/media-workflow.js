const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const TL = require('../lib/timeline');
const MW = require('../lib/media-workflow');
const project = { tl: TL.empty(), media: [], sequences: {} };
const clip = TL.addClip(project.tl, { path: '/missing/original.mp4', name: 'original.mp4', duration: 5 });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'frosty-media-workflow-'));
const newSource = path.join(tmp, 'relinked.mp4'); fs.writeFileSync(newSource, 'test');
const relink = MW.relinkMedia(project, { '/missing/original.mp4': newSource });
assert.strictEqual(relink.changed, 1); assert.strictEqual(clip.src, newSource);
assert.strictEqual(MW.validateTimeline(project.tl).valid, true);
clip.out = clip.in;
assert.strictEqual(MW.validateTimeline(project.tl).valid, false);
const repaired = MW.repairTimeline(project.tl);
assert(repaired.validation.valid, 'repair restores a valid source range');
const a = MW.createSequence(project, 'A'); const b = MW.createSequence(project, 'B');
TL.addClip(b, { path: newSource, name: 'relinked.mp4', duration: 2 });
assert(MW.canNest(project, a.id, b.id));
MW.addNestedSequence(project, a.id, b.id, 1);
assert(!MW.canNest(project, b.id, a.id), 'nested sequence graph prevents cycles');
assert.throws(() => MW.addNestedSequence(project, b.id, a.id, 0), /cycle/);
fs.rmSync(tmp, { recursive: true, force: true });
console.log('Media workflow checks passed');
